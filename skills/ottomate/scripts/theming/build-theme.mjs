// build-theme.mjs — Phase 0 WS0.2. The 3-tier semantic-token seam (spec §8).
//
// A minimal, dependency-free DTCG builder (the "or a minimal builder" the spec allows in place of
// Style Dictionary — keeps Phase 0 runnable in plain Node with no install). It:
//   1. loads a DTCG theme file (primitive -> semantic.<scheme> tiers),
//   2. resolves {alias} references (semantic -> primitive) into concrete values,
//   3. flattens ONE scheme into the semantic CSS custom properties a Block/Part reads, and
//   4. emits a `[data-theme="<name>"]` (light) + `[data-theme="<name>"].dark` (dark) CSS sheet.
//
// The contract (spec §8): Blocks read ONLY the semantic tier — --color-surface / --color-on-surface /
// --color-border / --color-action / --radius-* / --shadow-* / --motion-*. A theme = redefining the
// semantic tier under a selector; CSS vars recalc instantly. Ship 1 library + N themes.
//
// Reused by contrast-gate.mjs (resolvedColorMap) so the gate checks the SAME resolved values the CSS
// ships — one source of truth, not two.
//
// Usage:
//   node build-theme.mjs --theme cointrail.tokens.json --out cointrail.theme.css
//   node build-theme.mjs --theme cointrail.tokens.json --scheme light   # dump one scheme's vars

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** Walk a dotted path ("primitive.color.slate.900") to its node in the token tree. */
function nodeAt(tree, dotted) {
  return dotted.split('.').reduce((o, k) => (o == null ? undefined : o[k]), tree);
}

const ALIAS = /^\{(.+)\}$/;

/**
 * Resolve a token $value to a concrete value, following {alias} chains (with cycle + missing guards).
 * cubicBezier arrays and shadow strings pass through unchanged once no alias remains.
 */
export function resolveValue(theme, value, seen = new Set()) {
  if (typeof value === 'string') {
    const m = value.match(ALIAS);
    if (m) {
      const ref = m[1];
      if (seen.has(ref)) throw new Error(`token alias cycle at {${ref}}`);
      seen.add(ref);
      const target = nodeAt(theme, ref);
      if (!target || target.$value === undefined) throw new Error(`unresolved token alias {${ref}}`);
      return resolveValue(theme, target.$value, seen);
    }
  }
  return value;
}

export function loadTheme(file) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

/** Render a resolved DTCG value + its $type into a CSS value string. */
export function cssValue(type, value) {
  switch (type) {
    case 'cubicBezier':
      return `cubic-bezier(${value.join(', ')})`;
    case 'color':
    case 'dimension':
    case 'duration':
    case 'shadow':
    default:
      return String(value);
  }
}

// group -> the CSS-var prefix. color.surface -> --color-surface, motion.duration-fast -> --motion-duration-fast.
function cssVarName(group, leaf) {
  return `--${group}-${leaf}`;
}

/**
 * Flatten ONE scheme of the semantic tier into ordered CSS-var records. Only the semantic tier is
 * exposed — primitives are deliberately NOT emitted, so nothing downstream can read a raw ramp value.
 * @returns {Array<{path:string, cssVar:string, type:string, value:*, css:string}>}
 */
export function flattenScheme(theme, scheme) {
  const sem = theme.semantic?.[scheme];
  if (!sem) throw new Error(`theme has no semantic.${scheme} (schemes: ${Object.keys(theme.semantic ?? {}).join(', ')})`);
  const out = [];
  for (const group of Object.keys(sem)) {
    for (const leaf of Object.keys(sem[group])) {
      const tok = sem[group][leaf];
      if (!tok || tok.$value === undefined) continue;
      const value = resolveValue(theme, tok.$value);
      out.push({
        path: `${group}.${leaf}`,
        cssVar: cssVarName(group, leaf),
        type: tok.$type,
        value,
        css: cssValue(tok.$type, value),
      });
    }
  }
  return out;
}

/** path -> resolved hex, for colour tokens of one scheme. Consumed by the contrast gate. */
export function resolvedColorMap(theme, scheme) {
  const map = {};
  for (const r of flattenScheme(theme, scheme)) if (r.type === 'color') map[r.path] = r.value;
  return map;
}

function block(selector, records) {
  const body = records.map((r) => `  ${r.cssVar}: ${r.css};`).join('\n');
  return `${selector} {\n${body}\n}`;
}

/**
 * Emit the full theme sheet: light under `[data-theme="<name>"]`, dark under the same + `.dark`
 * (cointrail's real dark-mode convention — `@custom-variant dark (&:is(.dark *))`).
 */
export function emitCss(theme, { themeName = theme.$meta?.theme ?? 'theme' } = {}) {
  const light = flattenScheme(theme, 'light');
  const dark = flattenScheme(theme, 'dark');
  const header = `/* GENERATED by build-theme.mjs from ${theme.$meta?.source ?? 'a DTCG theme'} — do not edit by hand.\n`
    + `   theme="${themeName}" · semantic tier only · light + dark. Blocks read these vars, never a primitive. */`;
  return [
    header,
    block(`[data-theme="${themeName}"]`, light),
    block(`[data-theme="${themeName}"].dark`, dark),
    '',
  ].join('\n\n');
}

// ── CLI ────────────────────────────────────────────────────────────────────────────────────────
function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) out[a.slice(2)] = (argv[i + 1] && !argv[i + 1].startsWith('--')) ? argv[++i] : true;
  }
  return out;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.theme) { console.error('usage: node build-theme.mjs --theme <file.json> [--out <file.css>] [--scheme light|dark]'); process.exit(1); }
  const theme = loadTheme(args.theme);
  const name = theme.$meta?.theme ?? path.basename(args.theme).replace(/\..*$/, '');

  if (args.scheme) {
    const recs = flattenScheme(theme, args.scheme);
    console.log(`# ${name} · ${args.scheme} · ${recs.length} semantic tokens`);
    for (const r of recs) console.log(`${r.cssVar}: ${r.css};`);
    return;
  }
  const css = emitCss(theme, { themeName: name });
  if (args.out) {
    writeFileSync(args.out, css);
    console.log(`wrote ${args.out} (${(css.length / 1024).toFixed(1)} KB) · theme="${name}" · light+dark`);
  } else {
    process.stdout.write(css);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
